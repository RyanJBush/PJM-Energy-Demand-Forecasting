def test_failed_rollback_keeps_the_originals_and_says_where(prior_run, monkeypatch, capsys):
    p, calls, real = prior_run, {"n": 0}, sim_mod._move

    def dying(src, dst):
        calls["n"] += 1
        if calls["n"] >= 7:                                  # phase 2 fails, and so does every rollback move
            raise OSError("simulated disk failure")
        real(src, dst)

    monkeypatch.setattr(sim_mod, "_move", dying)
    code = main(["--csv", str(p["other"]), *p["args"]])
    err = capsys.readouterr().err
    assert code == 2 and "the rollback failed" in err and "preserved in" in err
    kept = sorted(p["tmp"].glob(".sim.staging-*"))
    assert len(kept) == 1                                    # retained on purpose; it is the only copy
    assert {n: (kept[0] / "backup" / n).read_bytes() for n in ARTIFACTS} == p["before"]


