def test_library_raises_after_fitting_and_freezing(no_common_csv):
    frozen = []
    with pytest.raises(NoCommonRowsError, match="no test hour could be scored for both forecasts") as e:
        run_simulation(read_observations(no_common_csv, "SYN"), on_freeze=frozen.append)
