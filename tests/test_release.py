def test_chart_contents(synth_run, tmp_path):
    pred, _ = synth_run
    out = tmp_path / "c.svg"
    assert chart_main(["--predictions", str(pred), "--origin", "2024-12-15T00:00:00Z", "--out", str(out)]) == 0
    text = out.read_text(encoding="utf-8")
    root = ET.fromstring(text)                                   # well-formed XML
    ns = "{http://www.w3.org/2000/svg}"
    assert "RETROSPECTIVE SIMULATION" in text and "SYNTHETIC test data, not real EIA data" in text
    assert "Demand (MW)" in text and "hour-ending UTC" in text
    polylines = root.findall(f"{ns}polyline")
    assert len(polylines) == 3 and all(len(pl.get("points").split()) == 24 for pl in polylines)
    assert len(root.findall(f"{ns}circle")) == 72
    ticks = [t.text for t in root.findall(f"{ns}text") if t.get("font-size") == "11" and t.text and len(t.text) == 2]
    assert ticks == [f"{h:02d}" for h in list(range(1, 24)) + [0]]          # 01 .. 23, then 00 (next midnight)
    assert "h24 = 00:00Z Dec 16, the following midnight" in text and "h1 = 01:00Z Dec 15" in text
    rows = [r for r in csv.DictReader(open(pred, newline="")) if r["origin_utc"] == "2024-12-15T00:00:00Z"]
    mae_b = sum(abs(float(r["baseline_forecast_mw"]) - float(r["actual_mw"])) for r in rows) / 24
    mae_r = sum(abs(float(r["ridge_forecast_mw"]) - float(r["actual_mw"])) for r in rows) / 24
    # the VISIBLE labels (tspans), not just the <desc>, must carry the right day MAE for each model
    shown = [t.text for t in root.iter(f"{ns}tspan")]
    assert shown == [f"weekly baseline {mae_b:,.2f} MW", f"ridge {mae_r:,.2f} MW"]


