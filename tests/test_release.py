def test_a_failing_invocation_during_another_ones_publication_does_not_disturb_it(prior_run, monkeypatch, capsys):
    """B starts and fails while A sits between 'all checks passed' and 'published'. With one shared staging
    directory, B's cleanup would have deleted A's staged files."""
    p, real_publish, inner = prior_run, sim_mod.publish, {}

    def publish_while_b_runs(new_dir, backup_dir, out_dir):
        bad = p["tmp"] / "bad.csv"
        write_series(bad, end=datetime(2024, 10, 31, 0))
        inner["b"] = main(["--csv", str(bad), *p["args"]])    # B: zero common rows, exit 1, cleans its own staging
        assert new_dir.exists() and sorted(os.listdir(new_dir)) == ARTIFACTS   # A's staged set survived B
        return real_publish(new_dir, backup_dir, out_dir)

    monkeypatch.setattr(sim_mod, "publish", publish_while_b_runs)
    assert main(["--csv", str(p["other"]), *p["args"]]) == 0
    capsys.readouterr()
    assert inner["b"] == 1
    after = _snapshot(p["out"])
    assert sorted(after) == ARTIFACTS and all(after[n] != p["before"][n] for n in ARTIFACTS)   # A published fully
    assert (json.loads(after["frozen_model.json"])["digest_sha256"]
            == json.loads(after["summary.json"])["frozen_digest_sha256"])
    assert not list(p["tmp"].glob(".sim.staging-*"))
