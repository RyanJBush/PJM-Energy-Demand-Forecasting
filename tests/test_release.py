@pytest.mark.parametrize("fail_at", range(1, 11))
def test_publication_error_at_any_step_leaves_prior_artifacts_intact(fail_at, prior_run, monkeypatch, capsys):
    p, calls, real = prior_run, {"n": 0}, sim_mod._move

    def flaky(src, dst):
        calls["n"] += 1
        if calls["n"] == fail_at:
            raise OSError(f"simulated publication failure at move {fail_at}")
        real(src, dst)                                       # every other move, including rollback, succeeds

    monkeypatch.setattr(sim_mod, "_move", flaky)
    code = main(["--csv", str(p["other"]), *p["args"]])
    cap = capsys.readouterr()
    assert code == 2
    assert f"simulated publication failure at move {fail_at}" in cap.err and "Traceback" not in cap.err
    assert cap.out == ""
    assert calls["n"] >= fail_at                             # the failure really happened mid-publication
    assert _snapshot(p["out"]) == p["before"]                # all five files, byte for byte
    _no_leftovers(p)
    monkeypatch.setattr(sim_mod, "_move", real)
    _rerun_would_change_everything(p, capsys)                # and the directory is still publishable afterwards


