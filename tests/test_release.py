ARTIFACTS = ["frozen_model.json", "paired_predictions.csv", "report.md", "summary.json", "validation.csv"]


@pytest.mark.parametrize("variant", list(VARIANTS))
def test_failed_rerun_preserves_the_complete_prior_artifact_set(variant, tmp_path, capsys):
    good, bad, out = tmp_path / "good.csv", tmp_path / "bad.csv", tmp_path / "sim"
    write_series(good)
    write_series(bad, shift=500.0, **VARIANTS[variant])   # shifted level: the fit differs from the good run
    args = ["--ba", "SYN", "--data-label", "synthetic", "--out-dir", str(out)]

    assert main(["--csv", str(good), *args, "--expect-common-rows", "1455"]) == 0
    capsys.readouterr()
    assert sorted(os.listdir(out)) == ARTIFACTS                            # the complete successful set
    before = {n: (out / n).read_bytes() for n in ARTIFACTS}
    good_digest = json.loads(before["summary.json"])["frozen_digest_sha256"]
    assert json.loads(before["frozen_model.json"])["digest_sha256"] == good_digest

    # same output directory, input that fits and tunes but has no hour scorable by both forecasts
    assert main(["--csv", str(bad), *args]) == 1
    cap = capsys.readouterr()
    assert cap.err.startswith("ERROR: no test hour could be scored for both forecasts.")
    assert "Fitting and tuning succeeded" in cap.err and "actuals present 0" in cap.err
    assert "Traceback" not in cap.err and cap.out == ""
    bad_digest = cap.err.split("digest ")[1].split(")")[0]
    assert bad_digest != good_digest        # the failed run did build a different frozen model...

    # ...and none of it leaked into the output directory: same files, same bytes, no leftovers
    assert sorted(os.listdir(out)) == ARTIFACTS
    assert {n: (out / n).read_bytes() for n in ARTIFACTS} == before
    assert json.loads((out / "frozen_model.json").read_text())["digest_sha256"] == good_digest
    assert sorted(os.listdir(tmp_path)) == ["bad.csv", "good.csv", "sim"]  # no staging directory left behind


